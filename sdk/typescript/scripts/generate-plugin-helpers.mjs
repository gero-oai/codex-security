import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import ts from "typescript";

const sourcePath = new URL(
  "../plugin-helpers-src/normalize-candidates.ts",
  import.meta.url,
);
const outputPath = new URL(
  "../_bundled_plugin/scripts/normalize_candidates.mjs",
  import.meta.url,
);
const { outputText } = ts.transpileModule(await readFile(sourcePath, "utf8"), {
  compilerOptions: {
    module: ts.ModuleKind.ESNext,
    target: ts.ScriptTarget.ES2022,
  },
});
const generated = await format(
  [
    "#!/usr/bin/env node",
    "// Generated from plugin-helpers-src/normalize-candidates.ts.",
    "// Do not edit this file directly.",
    "",
    outputText,
  ].join("\n"),
  { filepath: fileURLToPath(outputPath) },
);

if (process.argv[2] === "--check") {
  if ((await readFile(outputPath, "utf8")) !== generated) {
    throw new Error(
      "Generated plugin helpers are stale. Run `node scripts/generate-plugin-helpers.mjs`.",
    );
  }
} else {
  await writeFile(outputPath, generated, "utf8");
}
